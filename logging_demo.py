# -*- coding: utf-8 -*-

import logging


# ============================================================
# 1. 配置 logging
# ============================================================
logging.basicConfig(
    # INFO 表示：
    #
    # 只显示 INFO 及以上级别的日志。
    #
    # DEBUG    = 10，不显示
    # INFO     = 20，显示
    # WARNING  = 30，显示
    # ERROR    = 40，显示
    # CRITICAL = 50，显示
    level=logging.INFO,

    # 每条日志在控制台中的显示格式。
    format=(
        "%(asctime)s | "
        "%(levelname)s | "
        "%(name)s | "
        "%(message)s"
    ),

    # 控制时间的显示格式。
    datefmt="%H:%M:%S",
)


# ============================================================
# 2. 获取当前模块的 logger
# ============================================================
logger = logging.getLogger(__name__)


# ============================================================
# 3. 产生不同级别的日志
# ============================================================
logger.debug("这是一条 DEBUG 调试日志")

logger.info("相机开始打开")

logger.warning("曝光时间超过推荐范围")

logger.error("相机打开失败")


# ============================================================
# 4. 记录异常和完整调用栈
# ============================================================
try:
    result = 10 / 0

except Exception:
    logger.exception("计算过程中发生异常")